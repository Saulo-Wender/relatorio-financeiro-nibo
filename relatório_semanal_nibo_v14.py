def gerar_pdf_bytes(data, uploaded_logo, total_pago, total_apagar, diff):
    try:
        logo_temp_path = None
        if uploaded_logo:
            with tempfile.NamedTemporaryFile(delete=False, suffix=".png") as tmp:
                tmp.write(uploaded_logo.getvalue())
                logo_temp_path = tmp.name

        pdf = PDFPremium(logo_temp_path, data['periodo_txt'], "Relatório Financeiro Semanal")

        # CAPA
        kpis = {
            'pago': formatar_moeda_br(total_pago),
            'apagar': formatar_moeda_br(total_apagar),
            'diff': formatar_moeda_br(abs(diff)) + (" (Aumento)" if diff > 0 else " (Redução)")
        }
        pdf.cover_page(kpis)

        pdf.add_page() # Página de dados

        # TABELA 1: PAGOS
        pdf.section_title("Detalhamento: Contas Pagas")
        df_p = data['pagas']
        if not df_p.empty:
            cols_p_pdf = [data['cols_p']['data'], data['cols_p']['desc']]
            has_cat_p = data['cols_p']['cat'] in df_p.columns
            if has_cat_p: cols_p_pdf.append(data['cols_p']['cat'])

            full_p = df_p.sort_values(by=data['cols_p']['data']).copy()

            pdf_df_p = pd.DataFrame()
            pdf_df_p['Data'] = full_p[data['cols_p']['data']].dt.strftime('%d/%m')
            pdf_df_p['Fornecedor'] = full_p[data['cols_p']['desc']]
            if has_cat_p: pdf_df_p['Categoria'] = full_p[data['cols_p']['cat']]
            pdf_df_p['Valor'] = full_p['valor_final'].apply(formatar_moeda_br)

            pdf.create_table(pdf_df_p, include_cat=has_cat_p)

            # Resumo por Categoria (Se houver)
            if has_cat_p:
                pdf.ln(10)
                pdf.set_font('Arial', 'B', 11)
                pdf.cell(0, 10, "Resumo por Categoria:", 0, 1)
                resumo_cat = full_p.groupby(data['cols_p']['cat'])['valor_final'].sum().sort_values(ascending=False).reset_index()
                resumo_cat['valor_final'] = resumo_cat['valor_final'].apply(formatar_moeda_br)
                pdf.set_font('Arial', 'B', 9)
                pdf.cell(100, 7, "Categoria", 1)
                pdf.cell(40, 7, "Total", 1, 1)
                pdf.set_font('Arial', '', 9)
                for _, row in resumo_cat.iterrows():
                    cat_txt = str(row[0])[:50].encode('latin-1', 'replace').decode('latin-1')
                    pdf.cell(100, 7, cat_txt, 1)
                    pdf.cell(40, 7, str(row[1]), 1, 1)

        else:
            pdf.set_font("Arial", "", 10)
            pdf.cell(0, 10, "Sem registros.", 0, 1)

        pdf.ln(10)

        # TABELA 2: A PAGAR
        pdf.section_title("Previsão: Contas a Pagar")
        df_a = data['apagar']
        if not df_a.empty:
            cols_a_pdf = [data['cols_a']['data'], data['cols_a']['desc']]
            has_cat_a = data['cols_a']['cat'] in df_a.columns
            if has_cat_a: cols_a_pdf.append(data['cols_a']['cat'])

            full_a = df_a.sort_values(by=data['cols_a']['data']).copy()

            pdf_df_a = pd.DataFrame()
            pdf_df_a['Data'] = full_a[data['cols_a']['data']].dt.strftime('%d/%m')
            pdf_df_a['Fornecedor'] = full_a[data['cols_a']['desc']]
            if has_cat_a: pdf_df_a['Categoria'] = full_a[data['cols_a']['cat']]
            pdf_df_a['Valor'] = full_a['valor_final'].apply(formatar_moeda_br)

            pdf.create_table(pdf_df_a, include_cat=has_cat_a)
        else:
            pdf.set_font("Arial", "", 10)
            pdf.cell(0, 10, "Sem registros.", 0, 1)

        pdf_bytes = pdf.output(dest='S').encode('latin-1')
        if logo_temp_path: os.remove(logo_temp_path)
        return pdf_bytes

    except Exception as e:
        return None


