    def section_title(self, title):
        self.ln(10)
        self.set_font('Arial', 'B', 14)
        self.set_text_color(30, 64, 175)
        self.cell(0, 10, title.upper(), 0, 1, 'L')
        self.set_draw_color(30, 64, 175)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(5)

    def create_table(self, df, include_cat=False):
        # Configuração das Colunas
        if include_cat:
            headers = ["Data", "Fornecedor", "Categoria", "Valor"]
            widths = [25, 85, 45, 35]
        else:
            headers = ["Data", "Fornecedor", "Valor"]
            widths = [30, 115, 45]

        # Header Tabela
        self.set_font('Arial', 'B', 9)
        self.set_fill_color(241, 245, 249)
        self.set_text_color(33)
        self.set_draw_color(200)

        for i, h in enumerate(headers):
            self.cell(widths[i], 8, str(h), 1, 0, 'C', 1)
        self.ln()

        # Linhas
        self.set_font('Arial', '', 9)
        fill = False

        for _, row in df.iterrows():
            # Extração de dados segura
            dt = str(row[0])
            forn = str(row[1])[:50]
            try: forn = forn.encode('latin-1', 'replace').decode('latin-1')
            except: pass

            if include_cat:
                cat = str(row[2])[:25]
                try: cat = cat.encode('latin-1', 'replace').decode('latin-1')
                except: pass
                val = str(row[3])

                self.cell(widths[0], 7, dt, 1, 0, 'C', fill)
                self.cell(widths[1], 7, forn, 1, 0, 'L', fill)
                self.cell(widths[2], 7, cat, 1, 0, 'L', fill)
                self.cell(widths[3], 7, val, 1, 1, 'R', fill)
            else:
                val = str(row[2])
                self.cell(widths[0], 7, dt, 1, 0, 'C', fill)
                self.cell(widths[1], 7, forn, 1, 0, 'L', fill)
                self.cell(widths[2], 7, val, 1, 1, 'R', fill)

            self.ln()
            self.set_draw_color(230)
            self.line(10, self.get_y(), 200, self.get_y())

