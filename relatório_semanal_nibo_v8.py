class PDFReport(FPDF):
    def header(self):
        self.set_font('Arial', 'B', 16)
        self.cell(0, 10, 'Relatorio Financeiro Semanal', 0, 1, 'C')
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.cell(0, 10, f'Pagina {self.page_no()}', 0, 0, 'C')

def criar_pdf(kpis, top_pagos, top_apagar, periodo_txt):
    pdf = PDFReport()
    pdf.add_page()
    pdf.set_font("Arial", size=12)

