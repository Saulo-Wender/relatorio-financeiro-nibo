    pdf.ln(10)

    # KPIs
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "Resumo Executivo", 0, 1)
    pdf.set_font("Arial", size=12)
    pdf.cell(0, 10, f"Total Pago (Semana Passada): {kpis['pago']}", 0, 1)
    pdf.cell(0, 10, f"A Pagar (Esta Semana): {kpis['apagar']}", 0, 1)
    pdf.cell(0, 10, f"Variacao de Fluxo: {kpis['diff']}", 0, 1)
    pdf.ln(10)

    # Top Pagos
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "Maiores Pagamentos Realizados", 0, 1)
    pdf.set_font("Arial", size=10)
    # Cabeçalho Tabela
    pdf.set_fill_color(200, 220, 255)
    pdf.cell(100, 8, "Fornecedor", 1, 0, 'L', 1)
    pdf.cell(50, 8, "Valor", 1, 1, 'R', 1)
